#!/usr/bin/env bash
# =============================================================================
# Bahn Project Manager - UI/UX consistency, containerisation, real KPIs
#
# Self-extracting. Run it from the repository root on a checkout of db4f4ba
# ("stage 3: Projektanmeldung wizard"), which is what is on origin/main.
#
#   git checkout -b ui-consistency
#   git fetch origin main && git checkout origin/main -- uibootstrap.sh
#   bash uibootstrap.sh
#
# It verifies its own payload against a SHA-256 and refuses to apply a partial
# or corrupted download.
# =============================================================================
set -euo pipefail

EXPECTED_SHA="1621baa8784410ce4a8582ee607d5515409a0357db5d343daf6ca6f64cf419f3"

if [ ! -f package.json ] || [ ! -d client/src ]; then
  echo "!! run this from the repository root (package.json + client/src not found)" >&2
  exit 1
fi

# Refuse a second application. If this ever lands on main alongside the work
# it carries, `git checkout origin/main -- uibootstrap.sh` would hand you a
# bootstrap whose patch is already in your tree; git apply would fail halfway
# with a confusing conflict instead of saying so.
if [ -f shared/project-metrics.ts ]; then
  echo "!! already applied - shared/project-metrics.ts is present" >&2
  echo "   nothing to do; delete this script." >&2
  exit 0
fi

HEAD_SHA="$(git rev-parse HEAD)"
BASE="db4f4ba"
if ! git merge-base --is-ancestor "$BASE" HEAD 2>/dev/null; then
  echo "!! expected a checkout containing $BASE (stage 3). HEAD is $HEAD_SHA" >&2
  exit 1
fi

# Ignore this script itself: the documented way to fetch it is
#   git checkout origin/main -- uibootstrap.sh
# which stages the file, so it always shows up in `git status`.
DIRTY="$(git status --porcelain | grep -v "uibootstrap\.sh$" || true)"
if [ -n "$DIRTY" ]; then
  echo "!! working tree is dirty - commit or stash first" >&2
  echo "$DIRTY" >&2
  exit 1
fi

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

echo "==> extracting payload"
sed -n '/^__PAYLOAD__$/,$p' "$0" | tail -n +2 | base64 -d | gzip -d > "$TMP/ui.patch"

ACTUAL_SHA="$(sha256sum "$TMP/ui.patch" | cut -d' ' -f1)"
if [ "$ACTUAL_SHA" != "$EXPECTED_SHA" ]; then
  echo "!! checksum mismatch - the download is incomplete or corrupted" >&2
  echo "   expected $EXPECTED_SHA" >&2
  echo "   actual   $ACTUAL_SHA" >&2
  exit 1
fi
echo "    checksum ok"

echo "==> applying"
git apply --whitespace=nowarn "$TMP/ui.patch"
echo "    ok"

cat <<'EOF'
---------------------------------------------------------------------------
Applied. Quality gates:

  pnpm install
  pnpm check && pnpm lint && pnpm test:cov && pnpm verify:data \
    && NODE_ENV=production pnpm build:client

Expected:
  0 type errors
  93 lint warnings (was 263)
  88 passed / 6 skipped
  verify-data: all checks passed
  entry chunk 427.71 kB (was 771.76 kB)

Container (needs Docker):
  pnpm docker:build
  pnpm docker:up          # app + MySQL 8.4, http://localhost:3000
  curl -fsS localhost:3000/api/health

Then land it on main:
  git add -A && git commit -m "ui/ux consistency, containerisation, real KPIs"
  git checkout main && git pull --ff-only
  git merge --no-ff ui-consistency -m "ui/ux consistency, containerisation, real KPIs"
  git push && git branch -d ui-consistency
---------------------------------------------------------------------------
EOF
exit 0

