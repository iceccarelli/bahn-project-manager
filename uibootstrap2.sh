#!/usr/bin/env bash
# =============================================================================
# Bahn Project Manager - status vocabulary, DB brand red, validated ingest
#
# Run from the repository root on a checkout of origin/main at 3ead691.
#
#   git checkout -b consistency2
#   git fetch origin main && git checkout origin/main -- uibootstrap2.sh
#   bash uibootstrap2.sh
#
# Dash-free filename on purpose: GitHub's web upload strips dashes.
# =============================================================================
set -euo pipefail

EXPECTED_SHA="77401f0e59ad3e0fa807a48f6a005a4a08b695500dd69b4ef145140b6a8b359f"

if [ ! -f package.json ] || [ ! -d client/src ]; then
  echo "!! run this from the repository root" >&2; exit 1
fi

if [ -f shared/status-appearance.ts ]; then
  echo "!! already applied - shared/status-appearance.ts is present" >&2
  echo "   nothing to do; delete this script." >&2
  exit 0
fi

if [ ! -f shared/project-metrics.ts ]; then
  echo "!! prerequisite missing - this builds on the previous pass." >&2
  echo "   Expected shared/project-metrics.ts (origin/main at 3ead691)." >&2
  exit 1
fi

DIRTY="$(git status --porcelain | grep -v "uibootstrap2\.sh$" || true)"
if [ -n "$DIRTY" ]; then
  echo "!! working tree is dirty - commit or stash first" >&2
  echo "$DIRTY" >&2; exit 1
fi

TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT

echo "==> extracting payload"
sed -n '/^__PAYLOAD__$/,$p' "$0" | tail -n +2 | base64 -d | gzip -d > "$TMP/ui2.patch"

ACTUAL_SHA="$(sha256sum "$TMP/ui2.patch" | cut -d' ' -f1)"
if [ "$ACTUAL_SHA" != "$EXPECTED_SHA" ]; then
  echo "!! checksum mismatch - incomplete or corrupted download" >&2
  echo "   expected $EXPECTED_SHA" >&2
  echo "   actual   $ACTUAL_SHA" >&2
  exit 1
fi
echo "    checksum ok"

echo "==> applying"
git apply --whitespace=nowarn "$TMP/ui2.patch"
echo "    ok"

cat <<'EOF'
---------------------------------------------------------------------------
Applied. Quality gates:

  pnpm install
  pnpm check && pnpm lint && pnpm test:cov && pnpm verify:data \
    && NODE_ENV=production pnpm build:client

Expected:
  0 type errors
  85 lint warnings (was 87)
  108 passed / 6 skipped (was 88 passed)
  verify-data: all checks passed

No new dependencies, so `pnpm install` is a no-op here - it is in the list
only because leaving it out last time cost a failed build.

Then land it:
  git add -A && git commit -m "status vocabulary, DB brand red, validated ingest"
  git checkout main && git pull --ff-only
  git merge --no-ff consistency2 -m "status vocabulary, DB brand red, validated ingest"
  git push && git branch -d consistency2
---------------------------------------------------------------------------
EOF
exit 0

