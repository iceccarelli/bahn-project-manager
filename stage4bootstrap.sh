#!/usr/bin/env bash
# =============================================================================
# Bahn Project Manager - Stage 4a: contacts, ITK off-by-two fixed
#
#   git checkout -b stage4contacts
#   git fetch origin main && git checkout origin/main -- stage4bootstrap.sh
#   bash stage4bootstrap.sh
# =============================================================================
set -euo pipefail
EXPECTED_SHA="4ded9928dfa241ac6836972e2d24ce75bc00cf0b4e5f67ec1a99a902a8bf73a6"

[ -f package.json ] && [ -d client/src ] || { echo "!! run from the repository root" >&2; exit 1; }

if [ -f shared/contacts.ts ]; then
  echo "!! already applied - shared/contacts.ts is present" >&2; exit 0
fi
if [ ! -f shared/status-appearance.ts ]; then
  echo "!! prerequisite missing - expected origin/main at 33c32f1 or later" >&2; exit 1
fi

DIRTY="$(git status --porcelain | grep -v "stage4bootstrap\.sh$" || true)"
[ -z "$DIRTY" ] || { echo "!! working tree is dirty" >&2; echo "$DIRTY" >&2; exit 1; }

TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
echo "==> extracting payload"
sed -n '/^__PAYLOAD__$/,$p' "$0" | tail -n +2 | base64 -d | gzip -d > "$TMP/s4.patch"
ACTUAL="$(sha256sum "$TMP/s4.patch" | cut -d' ' -f1)"
[ "$ACTUAL" = "$EXPECTED_SHA" ] || { echo "!! checksum mismatch" >&2; echo "   expected $EXPECTED_SHA" >&2; echo "   actual   $ACTUAL" >&2; exit 1; }
echo "    checksum ok"
echo "==> applying"; git apply --whitespace=nowarn "$TMP/s4.patch"; echo "    ok"

cat <<'EOF'
---------------------------------------------------------------------------
Applied. Quality gates:

  pnpm check && pnpm lint && pnpm test:cov && pnpm verify:data \
    && NODE_ENV=production pnpm build:client

Expected:
  0 type errors
  85 lint warnings
  124 passed / 6 skipped   (was 108)
  verify-data adds: contacts: 51 Adressen | 13/14 Gewerke erreichbar
                    | ohne Adresse: LST

No new dependencies.

Then land it:
  git add -A && git commit -m "stage 4a: contacts, ITK off-by-two fixed"
  git checkout main && git pull --ff-only
  git merge --no-ff stage4contacts -m "stage 4a: contacts, ITK off-by-two fixed"
  git rm -f stage4bootstrap.sh && git commit -m "remove applied bootstrap artifact"
  git push && git branch -d stage4contacts
---------------------------------------------------------------------------
EOF
exit 0

